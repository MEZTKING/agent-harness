/**
 * Draws the main screens with made-up data (no network, no stored settings). With -Pscreenshots
 * each is saved as a PNG under app/build/screenshots; without it the test still proves they draw.
 */
@RunWith(RobolectricTestRunner::class)
@GraphicsMode(GraphicsMode.Mode.NATIVE)
@Config(sdk = [34], qualifiers = "w400dp-h860dp-xhdpi", application = android.app.Application::class)
class ScreensTest {
    private fun ago(h: Long) = Instant.now().minus(h, ChronoUnit.HOURS).toString()

    private val seats = listOf(
        SeatView("lantern-app", "running", "running · T5 of 9", "A made-up lantern app", lastActivity = ago(0), progress = Progress(5, 9),
            leftOff = "Structure previews in the live view", nextSteps = listOf("Check the glow", "Try the timer"), openTodos = 3, unread = 1),
        SeatView("quill-notes", "waiting", "1 high-priority to-do", "Notes with a quill", lastActivity = ago(3), openTodos = 4, high = 1, hasPlan = true),
        SeatView("me", "waiting", "idle · 2 h ago", lastActivity = ago(2), unread = 2),
        SeatView("stone-bridge", "idle", "idle · 2 days ago", lastActivity = ago(50), openTodos = 1),
        SeatView("ember-forge", "done", "done · 6 of 6", progress = Progress(6, 6), lastActivity = ago(20)),
        SeatView("tide-clock", "idle", "no status page yet"),
    )
    private val letter = Message("20261125T110000000000Z-bbbbbb", "quill-notes", "me", "ask", "Export presets: which three first?",
        "I can ship **three** presets first. Which ones?\n\n- Paper\n- Slate\n- Vellum", ago(1))
    private val needs = listOf(
        NeedView("msg:1", "message", "quill-notes", "Letter from quill-notes", letter.subject, listOf("read", "reply"), message = letter, at = ago(1)),
        NeedView("todo:a", "todo", "quill-notes", "To do: Check the Windows build", "quill-notes · high priority · from the journal"),
        NeedView("run:x", "run", "lantern-app", "Plan waits for your seal", "plan ready: 7 tasks, about \$0.85", listOf("approve")),
        NeedView("run:y", "run", "stone-bridge", "A task failed", "T3 failed after 3 attempts", listOf("retry", "skip")),
    )
    private val hall = HallState(seats, needs)

    private val status = StatusDoc.parse("""
        # quill-notes (example/quill-notes)

        Notes with a quill

        _Updated ${ago(3)} - generated by Roundtable Hold, don't edit by hand._

        ## Where we left off

        **${ago(4)}**: Shipped 0.4.0; the app `updates` itself

        - [ ] Check the parchment theme on a small phone
        - [ ] Try a real run

        ## To do

        - [ ] **(high)** Check the Windows build of 1.5.11 `fe069a`
        - [ ] Add prices under `pricing:` `e85317`

        ## Decisions

        - 2026-11-25: The paper look stays original: no assets from any game

        ## Done (latest first)

        - 2026-11-25: Released 0.4.0
    """.trimIndent())

    private val plan = PlanDoc.parse("""
        _Plan status: waiting for the owner · plan ready: 2 choices (about ${'$'}0.17, ~44 min) · updated ${ago(1)} by Roundtable Hold_

        # Plan v2: A lantern timer, as a web app.

        Build a small timer page with one chime.

        ## In scope
        - A start button
        - A chime

        ## Decisions
        ### What happens when time is up? [C1]
        - Ring once (recommended): A single chime. [Low] {a}
        - Ring until stopped: Keeps going until you press Stop. [Medium] {b}
        Why: Once is enough for a kitchen timer.

        ## Questions for the owner
        - Which colour for the lantern? {Q1}

        ## Ideas
        - [open] Add a dark mode. (Night use.) {I1}

        ## Tasks
        - [T1] pending Scaffold the page (coder)
    """.trimIndent())

    private fun shot(name: String, content: @Composable () -> Unit) {
        captureRoboImage("${System.getProperty("screenshots.dir") ?: "build/screenshots"}/$name.png") {
            RoundtableTheme { Box(Modifier.fillMaxSize().hallBackground()) { content() } }
        }
    }

    @Test fun table() = shot("1-table") {
        TableScreen(Load(hall), Mode.HUB, "Hub on GitHub · example/hub", emptySet(), {}, {}, { _, _ -> }, {}, false, {})
    }

    @Test fun tableWithManySeats() = shot("2-table-list") {
        val many = seats + seats.map { it.copy(id = it.id + "-2") }
        TableScreen(Load(hall.copy(seats = many)), Mode.HUB, "Hub on GitHub · example/hub", emptySet(), {}, {}, { _, _ -> }, {}, false, {})
    }

    @Test fun tableEmptyAndError() = shot("3-table-empty") {
        TableScreen(Load(HallState(), error = "Can't reach GitHub. Is the phone online?"), Mode.HUB, "Hub on GitHub", emptySet(), {}, {}, { _, _ -> }, {}, false, {})
    }

    @Test fun needsYou() = shot("4-needs-you") {
        NeedsList(needs, Mode.PC, emptySet(), { _, _ -> }, {}, Modifier.padding(16.dp), onClose = {})
    }

    @Test fun projectStatus() = shot("5-project-status") {
        ProjectScreen(ProjectUi("quill-notes", seats[1], Mode.HUB, "me", Load(status), Load(), Load(listOf(letter))), ProjectActions())
    }

    @Test fun projectPlan() = shot("6-project-plan") {
        ProjectScreen(ProjectUi("quill-notes", seats[1], Mode.HUB, "me", Load(status), Load(PlanView(plan, canApprove = true)), Load(),
            sent = mapOf("answer:Q1" to "Sent. Roundtable will reply in Letters.")), ProjectActions(), initialTab = 1)
    }

    @Test fun projectMessages() = shot("7-project-messages") {
        ProjectScreen(ProjectUi("quill-notes", seats[1], Mode.HUB, "me", Load(status), Load(), Load(listOf(letter, letter.copy(id = "2", read = true, subject = "Hub check")))),
            ProjectActions(), initialTab = 2)
    }

    @Test fun letters() = shot("8-letters") {
        LettersScreen(Load(listOf(letter, letter.copy(id = "2", sender = "lantern-app", subject = "Glow is done", read = true, created_at = ago(30)))),
            "me", seats.map { it.id }, {}, {}, { _, _, _, _ -> }, { _, _, _ -> })
    }
}
