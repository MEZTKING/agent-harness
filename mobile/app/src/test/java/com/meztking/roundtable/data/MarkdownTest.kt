package com.meztking.roundtable.data

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class MarkdownTest {
    private val status = """
        # lantern-app (example/lantern-app)

        A made-up project for the tests

        _Updated 2026-11-25T18:59:39Z - generated by Roundtable Hold, don't edit by hand._

        ## Where we left off

        **2026-11-25T13:41:57Z**: Shipped 0.4.0; the app `updates` itself

        - [ ] Check the lantern glows
        - [ ] Try a real run

        ## To do

        - [ ] **(high)** Set main as the default branch: Settings > General `fe069a`
        - [ ] Add prices under 'pricing:' `e85317`

        ## Future plans

        - Auto-scout new models `ac0c11`

        ## Decisions

        - 2026-11-25: Named it Lantern

        ## Done (latest first)

        - 2026-11-25: Released 0.4.0
    """.trimIndent()

    @Test fun statusPageHeaderAndSections() {
        val d = StatusDoc.parse(status)
        assertEquals("lantern-app (example/lantern-app)", d.title)
        assertEquals("A made-up project for the tests", d.description)
        assertEquals("2026-11-25T18:59:39Z", d.updated)
        assertEquals(listOf("Where we left off", "To do", "Future plans", "Decisions", "Done (latest first)"), d.sections.map { it.title })
    }

    @Test fun whereWeLeftOff() {
        val d = StatusDoc.parse(status)
        assertEquals("2026-11-25T13:41:57Z", d.leftOffAt)
        assertEquals("Shipped 0.4.0; the app `updates` itself", d.leftOff)
        assertEquals(listOf("Check the lantern glows", "Try a real run"), d.nextSteps)
    }

    @Test fun todosWithPriorityAndIds() {
        val t = StatusDoc.parse(status).todos
        assertEquals(2, t.size)
        assertTrue(t[0].high)
        assertEquals("Set main as the default branch: Settings > General", t[0].text)
        assertEquals("fe069a", t[0].id)
        assertFalse(t[1].high)
        assertEquals("e85317", t[1].id)
    }

    @Test fun emptyAndNothingOpen() {
        assertTrue(StatusDoc.parse("").isEmpty)
        val d = StatusDoc.parse("# me\n\n_Updated 2026-11-25T21:19:05Z - x._\n\n## To do\n\n_Nothing open._\n")
        assertEquals(0, d.todos.size)
        assertEquals("", d.leftOff)
        assertEquals("2026-11-25T21:19:05Z", d.updated)
    }

    @Test fun blocks() {
        val b = Markdown.parse("## Head\n\n- [x] done item\n  - nested\n1. first\n> quoted\n\n```\ncode\n```\n---\n| a | b |\n|---|---|\n| 1 | 2 |\npara\ncontinues")
        assertEquals(Md.Heading(2, "Head"), b[0])
        assertEquals(Md.Item("done item", checked = true), b[1])
        assertEquals(Md.Item("nested", depth = 1), b[2])
        assertEquals(Md.Item("first", number = 1), b[3])
        assertEquals(Md.Quote("quoted"), b[4])
        assertEquals(Md.Code("code"), b[5])
        assertEquals(Md.Rule, b[6])
        assertEquals(Md.Table(listOf(listOf("a", "b"), listOf("1", "2"))), b[7])
        assertEquals(Md.Paragraph("para continues"), b[8])
    }

    @Test fun inlineSpans() {
        val s = Markdown.inline("a **bold** and _it_ and `code` and [link](https://x.y) snake_case_word")
        assertEquals(
            listOf(
                Inline.Plain("a "), Inline.Bold("bold"), Inline.Plain(" and "), Inline.Italic("it"), Inline.Plain(" and "),
                Inline.Code("code"), Inline.Plain(" and "), Inline.Link("link", "https://x.y"), Inline.Plain(" snake_case_word"),
            ),
            s,
        )
        assertEquals("plain bold", Markdown.plain("plain **bold**"))
        // an unclosed mark stays as text
        assertEquals(listOf(Inline.Plain("2 * 3 and `open")), Markdown.inline("2 * 3 and `open"))
    }

    @Test fun ids() {
        assertEquals("text" to "Q1", Markdown.splitId("text {Q1}"))
        assertEquals("text" to "abc123", Markdown.splitId("text `abc123`"))
        assertEquals("text `not an id!`" to null, Markdown.splitId("text `not an id!`"))
        assertNull(Markdown.splitId("no id here").second)
    }

    @Test fun ago() {
        val now = java.time.Instant.parse("2026-11-25T12:00:00Z")
        assertEquals("just now", ago("2026-11-25T11:59:30Z", now))
        assertEquals("5 min ago", ago("2026-11-25T11:55:00Z", now))
        assertEquals("3 h ago", ago("2026-11-25T09:00:00Z", now))
        assertEquals("3 days ago", ago("2026-11-22T09:00:00Z", now))
        assertEquals("2 h ago", ago("2026-11-25T10:00", now))
        assertEquals("Mc", initialsOf("mcsupermods"))
        assertEquals("Ah", initialsOf("agent-harness"))
    }
}
